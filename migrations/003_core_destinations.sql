CREATE TABLE public.core_projects (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL, description text NOT NULL,
    status varchar(16) NOT NULL CHECK (status IN ('idea','planning','active','paused','completed','archived')),
    progress integer NOT NULL CHECK (progress BETWEEN 0 AND 100),
    milestone varchar(200) NOT NULL, target_date date, updated_at timestamptz NOT NULL
);
-- Life Planner Desktop usa già questo nome e gli stessi campi.
CREATE TABLE IF NOT EXISTS public.life_events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(180) NOT NULL, category varchar(30) NOT NULL, starts_at timestamptz NOT NULL,
    ends_at timestamptz, location varchar(180) NOT NULL, description text NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_life_events_starts_at ON public.life_events(starts_at);
CREATE INDEX ix_core_projects_updated ON public.core_projects(updated_at);
ALTER TABLE public.core_projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.life_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inbox_items
    ADD COLUMN project_id integer REFERENCES public.core_projects(id) ON DELETE SET NULL,
    ADD COLUMN task_id integer REFERENCES public.academic_tasks(id) ON DELETE SET NULL,
    ADD COLUMN event_id integer REFERENCES public.life_events(id) ON DELETE SET NULL;

-- Le API FastAPI usano il ruolo backend. Il catalogo resta privato anche con
-- eventuali privilegi predefiniti impostati da Supabase sulle nuove tabelle.
DO $$
DECLARE
    object_name text;
    app_role text;
    identity_sequence text;
BEGIN
    FOREACH object_name IN ARRAY ARRAY['core_projects','life_events','core_notifications','inbox_items','nexus_core_migrations']
    LOOP
        EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM PUBLIC', object_name);
        identity_sequence := CASE WHEN object_name = 'nexus_core_migrations' THEN NULL
            ELSE pg_get_serial_sequence(format('public.%I', object_name), 'id') END;
        IF identity_sequence IS NOT NULL THEN
            EXECUTE format('REVOKE ALL PRIVILEGES ON SEQUENCE %s FROM PUBLIC', identity_sequence);
        END IF;
        FOR app_role IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated')
        LOOP
            EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM %I', object_name, app_role);
            IF identity_sequence IS NOT NULL THEN
                EXECUTE format('REVOKE ALL PRIVILEGES ON SEQUENCE %s FROM %I', identity_sequence, app_role);
            END IF;
        END LOOP;
    END LOOP;
END $$;
