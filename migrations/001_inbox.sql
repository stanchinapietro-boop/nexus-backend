-- Applicare una volta con il ruolo del backend, sullo stesso database di notes.
CREATE TABLE public.inbox_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id varchar(36) NOT NULL UNIQUE,
    request_hash varchar(64) NOT NULL,
    title varchar(200) NOT NULL,
    content text NOT NULL,
    kind varchar(16) NOT NULL CHECK (kind IN ('task','idea','note','reminder','event','expense','project','other')),
    status varchar(16) NOT NULL CHECK (status IN ('new','processing','archived','completed')),
    tags jsonb NOT NULL CHECK (jsonb_typeof(tags) = 'array'),
    due_date date,
    source varchar(80) NOT NULL,
    destination varchar(80),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    converted_at timestamptz,
    note_id integer REFERENCES public.notes(id) ON DELETE SET NULL
);
CREATE INDEX ix_inbox_items_status_created ON public.inbox_items (status, created_at);
ALTER TABLE public.inbox_items ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.inbox_items FROM PUBLIC;
DO $$
DECLARE r text;
BEGIN
    FOR r IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon','authenticated')
    LOOP
        EXECUTE format('REVOKE ALL ON public.inbox_items FROM %I', r);
        EXECUTE format('REVOKE ALL ON SEQUENCE public.inbox_items_id_seq FROM %I', r);
    END LOOP;
END $$;
