-- PostgreSQL / Supabase. Eseguire prima del deploy del backend Milestone 02.
-- La tabella notes deve già esistere. La migrazione non tocca le note storiche.
CREATE TABLE IF NOT EXISTS public.core_notifications (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category varchar(24) NOT NULL,
    title varchar(200) NOT NULL,
    message varchar(500) NOT NULL,
    note_id integer UNIQUE REFERENCES public.notes(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at timestamptz
);
ALTER TABLE public.core_notifications ENABLE ROW LEVEL SECURITY;
CREATE INDEX IF NOT EXISTS ix_core_notifications_read_id
    ON public.core_notifications (read_at, id);
CREATE INDEX IF NOT EXISTS ix_core_notifications_category_id
    ON public.core_notifications (category, id);

CREATE OR REPLACE FUNCTION public.nexus_notify_note_insert() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    INSERT INTO public.core_notifications (category, title, message, note_id)
    VALUES ('system', 'Nota salvata', NEW.title, NEW.id);
    RETURN NEW;
END;
$$;
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.notes'::regclass AND tgname = 'nexus_note_added'
    ) THEN
        CREATE TRIGGER nexus_note_added AFTER INSERT ON public.notes
        FOR EACH ROW EXECUTE FUNCTION public.nexus_notify_note_insert();
    END IF;
END;
$$;
